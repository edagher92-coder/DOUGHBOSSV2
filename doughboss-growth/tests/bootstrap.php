if ( ! function_exists( 'shortcode_parse_atts' ) ) {
	/**
	 * Simplified: name="v", name='v', name=v and bare words.
	 *
	 * @param string $text Attribute text.
	 * @return array
	 */
	function shortcode_parse_atts( $text ) {
		$atts = array();
		if ( preg_match_all( '/([A-Za-z0-9_-]+)\s*=\s*(?:"([^"]*)"|\'([^\']*)\'|([^\s"\']+))|"([^"]*)"|(\S+)/', (string) $text, $matches, PREG_SET_ORDER ) ) {
			foreach ( $matches as $match ) {
				if ( ! empty( $match[1] ) ) {
					$value = '' !== ( isset( $match[2] ) ? $match[2] : '' ) ? $match[2] : ( ( isset( $match[3] ) && '' !== $match[3] ) ? $match[3] : ( isset( $match[4] ) ? $match[4] : '' ) );
					$atts[ $match[1] ] = $value;
				} elseif ( isset( $match[5] ) && '' !== $match[5] ) {
					$atts[] = $match[5];
				} elseif ( isset( $match[6] ) ) {
					$atts[] = $match[6];
				}
			}
		}
		return $atts;
	}
}
if ( ! function_exists( 'do_shortcode' ) ) {
	/**
	 * Self-closing and enclosing shortcodes; applies the do_shortcode_tag filter like WordPress.
	 *
	 * @param string $content Content.
	 * @return string
	 */
	function do_shortcode( $content ) {
		$tags = array_keys( $GLOBALS['dbgr_shortcodes'] );
		if ( array() === $tags ) {
			return (string) $content;
		}
		$names   = implode( '|', array_map( 'preg_quote', $tags ) );
		$pattern = '/\[(' . $names . ')((?:\s[^\]]*)?)\](?:(.*?)\[\/\1\])?/s';
		return preg_replace_callback(
			$pattern,
			function ( $m ) {
				$tag    = $m[1];
				$attr   = shortcode_parse_atts( trim( $m[2] ) );
				$body   = isset( $m[3] ) ? $m[3] : '';
				$output = (string) call_user_func( $GLOBALS['dbgr_shortcodes'][ $tag ], $attr, $body, $tag );
				return (string) apply_filters( 'do_shortcode_tag', $output, $tag, $attr, $m );
			},
			(string) $content
		);
	}
}

