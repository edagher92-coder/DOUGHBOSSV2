	 * Supports add_query_arg( array, url ) and add_query_arg( key, value, url ).
	 *
	 * @return string
	 */
	function add_query_arg() {
		$args = func_get_args();
		if ( is_array( $args[0] ) ) {
			$params = $args[0];
			$url    = isset( $args[1] ) ? (string) $args[1] : '';
		} else {
			$params = array( $args[0] => isset( $args[1] ) ? $args[1] : '' );
			$url    = isset( $args[2] ) ? (string) $args[2] : '';
		}
		$fragment = '';
		if ( false !== strpos( $url, '#' ) ) {
			list( $url, $fragment ) = explode( '#', $url, 2 );
			$fragment               = '#' . $fragment;
		}
		$query = '';
		if ( false !== strpos( $url, '?' ) ) {
			list( $url, $query ) = explode( '?', $url, 2 );
		}
		parse_str( $query, $existing );
		$merged = array_merge( $existing, $params );
		$merged = array_filter(
			$merged,
			function ( $v ) {
				return false !== $v && null !== $v;
			}
		);
		return $url . ( array() === $merged ? '' : '?' . http_build_query( $merged, '', '&', PHP_QUERY_RFC3986 ) ) . $fragment;
	}
}
