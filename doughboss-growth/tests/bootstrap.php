		DoughBoss_Growth_Outbox::reset_handlers();
	}
	if ( class_exists( 'DoughBoss_Growth_Admin' ) ) {
		DoughBoss_Growth_Admin::reset_tabs();
	}
}

/**
 * Declare and run one test case. State is reset first.
 *
 * @param string   $name Test name.
 * @param callable $body Test body.
 * @return void
 */
function db_test( $name, $body ) {
	$GLOBALS['doughboss_test_results']['current'] = $name;
	dbgr_test_reset();
	try {
		call_user_func( $body );
	} catch ( Exception $e ) {
		db_fail( 'threw ' . get_class( $e ) . ': ' . $e->getMessage() );
	} catch ( Error $e ) {
		db_fail( 'fatal ' . get_class( $e ) . ': ' . $e->getMessage() . ' @ ' . basename( $e->getFile() ) . ':' . $e->getLine() );
	}
	$GLOBALS['doughboss_test_results']['current'] = '';
}

/**
 * Record a failure against the current test.
 *
 * @param string $detail Failure detail.
 * @return void
 */
function db_fail( $detail ) {
	$GLOBALS['doughboss_test_results']['failed']++;
	$GLOBALS['doughboss_test_results']['failures'][] = $GLOBALS['doughboss_test_results']['current'] . ' - ' . $detail;
}

/**
 * Record a pass.
 *
 * @return void
 */
function db_pass() {
	$GLOBALS['doughboss_test_results']['passed']++;
}

/**
 * Record a skipped check (the environment cannot run it). A skip is not a pass: run.php lists every skip.
 *
 * @param string $reason Why the check could not run.
 * @return void
 */
function dbgr_test_skip( $reason ) {
	$GLOBALS['doughboss_test_results']['skipped'][] = $GLOBALS['doughboss_test_results']['current'] . ' - ' . $reason;
}

/**
 * Assert strict equality.
 *
 * @param mixed  $expected Expected.
 * @param mixed  $actual   Actual.
 * @param string $message  Label.
 * @return void
 */
function assert_same( $expected, $actual, $message ) {
	if ( $expected === $actual ) {
		db_pass();
		return;
	}
	db_fail( $message . ' (expected ' . var_export( $expected, true ) . ', got ' . var_export( $actual, true ) . ')' );
}

/**
 * Assert truthy.
 *
 * @param mixed  $actual  Actual.
 * @param string $message Label.
 * @return void
 */
function assert_true( $actual, $message ) {
	assert_same( true, (bool) $actual, $message );
}

/**
 * Assert falsy.
 *
 * @param mixed  $actual  Actual.
 * @param string $message Label.
 * @return void
 */
function assert_false( $actual, $message ) {
	assert_same( false, (bool) $actual, $message );
}

/**
 * Assert a string contains a substring.
 *
 * @param string $needle   Needle.
 * @param string $haystack Haystack.
 * @param string $message  Label.
 * @return void
 */
function assert_contains( $needle, $haystack, $message ) {
	if ( is_string( $haystack ) && '' !== $needle && false !== strpos( $haystack, $needle ) ) {
		db_pass();
		return;
	}
	db_fail( $message . ' (expected to contain ' . var_export( $needle, true ) . ' in ' . var_export( is_string( $haystack ) ? substr( $haystack, 0, 300 ) : $haystack, true ) . ')' );
}

/**
 * Assert a string does not contain a substring.
 *
 * @param string $needle   Needle.
 * @param string $haystack Haystack.
 * @param string $message  Label.
 * @return void
 */
function assert_not_contains( $needle, $haystack, $message ) {
	if ( is_string( $haystack ) && false === strpos( $haystack, $needle ) ) {
		db_pass();
		return;
	}
	db_fail( $message . ' (must not contain ' . var_export( $needle, true ) . ')' );
}

/**
 * Assert a regex matches.
 *
 * @param string $pattern Pattern.
 * @param string $subject Subject.
 * @param string $message Label.
 * @return void
 */
function assert_matches( $pattern, $subject, $message ) {
	if ( is_string( $subject ) && 1 === preg_match( $pattern, $subject ) ) {
		db_pass();
		return;
	}
	db_fail( $message . ' (pattern ' . $pattern . ' did not match ' . var_export( is_string( $subject ) ? substr( $subject, 0, 300 ) : $subject, true ) . ')' );
}

/**
 * Assert a countable has an exact size.
 *
 * @param int    $expected Size.
 * @param mixed  $actual   Array.
 * @param string $message  Label.
 * @return void
 */
function assert_count( $expected, $actual, $message ) {
	assert_same( $expected, is_array( $actual ) ? count( $actual ) : -1, $message );
}

/**
 * Assert that a callable throws a given exception class.
 *
 * @param string   $class   Exception class.
 * @param callable $fn      Callable.
 * @param string   $message Label.
 * @return mixed The exception, or null.
 */
function assert_throws( $class, $fn, $message ) {
	try {
		call_user_func( $fn );
	} catch ( Exception $e ) {
		if ( $e instanceof $class ) {
			db_pass();
			return $e;
		}
		db_fail( $message . ' (threw ' . get_class( $e ) . ', expected ' . $class . ')' );
		return $e;
	}
	db_fail( $message . ' (nothing thrown, expected ' . $class . ')' );
	return null;
}

/**
 * Negative control for the harness itself: run a callable that SHOULD cause test failures (for example
 * an unexpected HTTP call) and assert that at least one failure was recorded. The failures it produced
 * are then removed so they do not fail the suite; a callable that fails nothing is itself a failure.
 *
 * @param callable $fn      Callable expected to trip the harness.
 * @param string   $message Label.
 * @return int Number of failures that were absorbed.
 */
function dbgr_test_expect_failure( $fn, $message ) {
	$before_failed   = $GLOBALS['doughboss_test_results']['failed'];
	$before_failures = count( $GLOBALS['doughboss_test_results']['failures'] );
	try {
		call_user_func( $fn );
	} catch ( Exception $e ) {
		db_fail( $message . ' (threw instead of failing: ' . $e->getMessage() . ')' );
	}
	$absorbed = $GLOBALS['doughboss_test_results']['failed'] - $before_failed;
	$GLOBALS['doughboss_test_results']['failed']   = $before_failed;
	$GLOBALS['doughboss_test_results']['failures'] = array_slice( $GLOBALS['doughboss_test_results']['failures'], 0, $before_failures );
	assert_true( $absorbed > 0, $message . ' (the harness must flag it)' );
	return $absorbed;
}

