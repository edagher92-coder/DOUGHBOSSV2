if ( ! function_exists( 'has_filter' ) ) {
	/**
	 * @param string        $hook     Hook.
	 * @param callable|bool $callback Callback to look for.
	 * @return bool|int
	 */
	function has_filter( $hook, $callback = false ) {
		if ( empty( $GLOBALS['dbgr_hooks'][ $hook ] ) ) {
			return false;
		}
		if ( false === $callback ) {
			return true;
		}
		$id = dbgr_hook_id( $callback );
		foreach ( $GLOBALS['dbgr_hooks'][ $hook ] as $priority => $callbacks ) {
			if ( isset( $callbacks[ $id ] ) ) {
				return (int) $priority;
			}
		}
		return false;
	}
}
if ( ! function_exists( 'has_action' ) ) {
	/**
	 * @param string        $hook     Hook.
	 * @param callable|bool $callback Callback.
	 * @return bool|int
	 */
	function has_action( $hook, $callback = false ) {
		return has_filter( $hook, $callback );
	}
}
if ( ! function_exists( 'remove_filter' ) ) {
	/**
	 * @param string   $hook     Hook.
	 * @param callable $callback Callback.
	 * @param int      $priority Priority.
	 * @return bool
	 */
	function remove_filter( $hook, $callback, $priority = 10 ) {
		$id = dbgr_hook_id( $callback );
		if ( isset( $GLOBALS['dbgr_hooks'][ $hook ][ (int) $priority ][ $id ] ) ) {
			unset( $GLOBALS['dbgr_hooks'][ $hook ][ (int) $priority ][ $id ] );
			return true;
		}
		return false;
	}
}
if ( ! function_exists( 'remove_action' ) ) {
	/**
	 * @param string   $hook     Hook.
	 * @param callable $callback Callback.
	 * @param int      $priority Priority.
	 * @return bool
	 */
	function remove_action( $hook, $callback, $priority = 10 ) {
		return remove_filter( $hook, $callback, $priority );
	}
}
if ( ! function_exists( 'remove_all_filters' ) ) {
	/**
	 * @param string   $hook     Hook.
