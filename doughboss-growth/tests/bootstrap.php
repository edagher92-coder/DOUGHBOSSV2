	function remove_all_filters( $hook, $priority = false ) {
		if ( false === $priority ) {
			unset( $GLOBALS['dbgr_hooks'][ $hook ] );
		} else {
			unset( $GLOBALS['dbgr_hooks'][ $hook ][ (int) $priority ] );
		}
		return true;
	}
