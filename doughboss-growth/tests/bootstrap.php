	public $prepared_sql = array();
	/** @var array Statements executed that did not come from prepare(). */
	public $unprepared = array();
	/** @var array Writes outside the companion namespace. */
	public $foreign_writes = array();
	/** @var array Tables known to exist (non-SQLite mode). */
	public $tables_created = array();
	/** @var bool */
	public $fail_all = false;
	/** @var array */
	private $responders = array();
	/** @var array */
	private $fail_patterns = array();
	/** @var PDO|null */
	private $pdo = null;

	/** @return string */
