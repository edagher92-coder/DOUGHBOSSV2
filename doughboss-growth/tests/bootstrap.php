	$GLOBALS['dbgr_mail_fails']   = false;
	$GLOBALS['dbgr_http']         = array( 'expect' => array(), 'calls' => array() );
	$GLOBALS['dbgr_applied']      = array();
	$GLOBALS['dbgr_done']         = array();
	$GLOBALS['dbgr_current']      = array();
	$GLOBALS['dbgr_assets']       = array( 'scripts' => array(), 'styles' => array(), 'inline' => array(), 'localized' => array() );
	$GLOBALS['dbgr_headers']      = array();
	if ( is_array( $GLOBALS['dbgr_hooks_baseline'] ) ) {
		$GLOBALS['dbgr_hooks'] = $GLOBALS['dbgr_hooks_baseline'];
	} else {
		$GLOBALS['dbgr_hooks'] = array();
