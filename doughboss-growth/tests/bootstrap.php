/**
 * Internal: route one request through the expectations.
 *
 * @param string $method Method.
 * @param string $url    URL.
 * @param array  $args   Args.
 * @return array|WP_Error
 */
function dbgr_test_http_dispatch( $method, $url, $args ) {
	$method = strtoupper( $method );
	foreach ( $GLOBALS['dbgr_http']['expect'] as $index => $entry ) {
		if ( '' !== $entry['method'] && $entry['method'] !== $method ) {
			continue;
		}
		if ( $entry['times'] > 0 && $entry['used'] >= $entry['times'] ) {
			continue;
		}
		$pattern = $entry['url'];
		$match   = false;
		if ( '#' === substr( $pattern, 0, 1 ) ) {
			$match = 1 === preg_match( $pattern, $url );
		} elseif ( '*' === substr( $pattern, -1 ) ) {
			$match = 0 === strpos( $url, substr( $pattern, 0, -1 ) );
		} else {
			$match = ( $pattern === $url );
		}
		if ( ! $match ) {
			continue;
		}
		$GLOBALS['dbgr_http']['expect'][ $index ]['used']++;
		$GLOBALS['dbgr_http']['calls'][] = array( 'method' => $method, 'url' => $url, 'args' => $args, 'unexpected' => false );
		$response                        = $entry['response'];
		return is_callable( $response ) ? call_user_func( $response, $url, $args ) : $response;
	}
	$GLOBALS['dbgr_http']['calls'][] = array( 'method' => $method, 'url' => $url, 'args' => $args, 'unexpected' => true );
	$shown                           = preg_replace( '/\?.*$/', '?[query]', $url );
	db_fail( 'UNEXPECTED HTTP CALL: ' . $method . ' ' . $shown );
	return new WP_Error( 'dbgr_unexpected_http', 'Unexpected HTTP call in test.' );
}

