$GLOBALS['dbgr_hooks'] = array();

/**
 * Unique id for a callback, as WordPress derives it.
 *
 * @param callable $callback Callback.
 * @return string
 */
function dbgr_hook_id( $callback ) {
	if ( is_string( $callback ) ) {
		return $callback;
	}
	if ( is_object( $callback ) ) {
		return spl_object_hash( $callback );
	}
	if ( is_array( $callback ) ) {
		if ( is_object( $callback[0] ) ) {
			return spl_object_hash( $callback[0] ) . '::' . $callback[1];
		}
		return $callback[0] . '::' . $callback[1];
	}
	return serialize( $callback );
}

if ( ! function_exists( 'add_filter' ) ) {
	/**
	 * @param string   $hook          Hook.
	 * @param callable $callback      Callback.
	 * @param int      $priority      Priority.
	 * @param int      $accepted_args Accepted args.
	 * @return true
	 */
	function add_filter( $hook, $callback, $priority = 10, $accepted_args = 1 ) {
		$GLOBALS['dbgr_hooks'][ $hook ][ (int) $priority ][ dbgr_hook_id( $callback ) ] = array(
			'fn'   => $callback,
			'args' => (int) $accepted_args,
		);
		return true;
	}
}
if ( ! function_exists( 'add_action' ) ) {
	/**
	 * @param string   $hook          Hook.
	 * @param callable $callback      Callback.
	 * @param int      $priority      Priority.
	 * @param int      $accepted_args Accepted args.
	 * @return true
	 */
	function add_action( $hook, $callback, $priority = 10, $accepted_args = 1 ) {
		return add_filter( $hook, $callback, $priority, $accepted_args );
	}
}
if ( ! function_exists( 'apply_filters' ) ) {
	/**
	 * @param string $hook  Hook.
	 * @param mixed  $value Value.
	 * @param mixed  ...$args Extra args.
	 * @return mixed
	 */
	function apply_filters( $hook, $value, ...$args ) {
		$GLOBALS['dbgr_applied'][ $hook ] = ( isset( $GLOBALS['dbgr_applied'][ $hook ] ) ? $GLOBALS['dbgr_applied'][ $hook ] : 0 ) + 1;
		if ( empty( $GLOBALS['dbgr_hooks'][ $hook ] ) ) {
			return $value;
		}
		$GLOBALS['dbgr_current'][] = $hook;
		$priorities                = $GLOBALS['dbgr_hooks'][ $hook ];
		ksort( $priorities );
		foreach ( $priorities as $callbacks ) {
			foreach ( $callbacks as $entry ) {
				$call_args = array_merge( array( $value ), $args );
				$call_args = ( 0 === $entry['args'] ) ? array() : array_slice( $call_args, 0, $entry['args'] );
				$value     = call_user_func_array( $entry['fn'], $call_args );
			}
		}
		array_pop( $GLOBALS['dbgr_current'] );
		return $value;
	}
}
if ( ! function_exists( 'apply_filters_ref_array' ) ) {
	/**
	 * @param string $hook Hook.
	 * @param array  $args Args (first is the value).
	 * @return mixed
	 */
	function apply_filters_ref_array( $hook, $args ) {
		$value = array_shift( $args );
		return apply_filters( $hook, $value, ...$args );
	}
}
if ( ! function_exists( 'do_action' ) ) {
	/**
	 * @param string $hook    Hook.
	 * @param mixed  ...$args Args.
	 * @return void
	 */
	function do_action( $hook, ...$args ) {
		$GLOBALS['dbgr_done'][ $hook ] = ( isset( $GLOBALS['dbgr_done'][ $hook ] ) ? $GLOBALS['dbgr_done'][ $hook ] : 0 ) + 1;
		if ( empty( $GLOBALS['dbgr_hooks'][ $hook ] ) ) {
			return;
		}
		$GLOBALS['dbgr_current'][] = $hook;
		$priorities                = $GLOBALS['dbgr_hooks'][ $hook ];
		ksort( $priorities );
		foreach ( $priorities as $callbacks ) {
			foreach ( $callbacks as $entry ) {
				$call_args = ( 0 === $entry['args'] ) ? array() : array_slice( $args, 0, $entry['args'] );
				call_user_func_array( $entry['fn'], $call_args );
			}
		}
		array_pop( $GLOBALS['dbgr_current'] );
	}
}
