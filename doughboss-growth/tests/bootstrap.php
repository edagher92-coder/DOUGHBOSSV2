if ( ! function_exists( 'wp_verify_nonce' ) ) {
	/** @param string $nonce Nonce. @param string $action Action. @return int|false */
	function wp_verify_nonce( $nonce, $action = '-1' ) {
		$nonce = (string) $nonce;
		if ( '' === $nonce ) {
			return false;
		}
		$tick = (int) floor( dbgr_test_now() / 43200 );
		foreach ( array( 1 => $tick, 2 => $tick - 1 ) as $result => $t ) {
			$expected = substr( hash_hmac( 'sha256', $t . '|' . $action . '|' . get_current_user_id(), wp_salt( 'nonce' ) ), 0, 10 );
			if ( hash_equals( $expected, $nonce ) ) {
				return $result;
			}
		}
		return false;
	}
}
