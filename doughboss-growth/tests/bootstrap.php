	}
}
if ( ! function_exists( 'current_filter' ) ) {
	/** @return string */
	function current_filter() {
		return empty( $GLOBALS['dbgr_current'] ) ? '' : end( $GLOBALS['dbgr_current'] );
	}
}

/**
 * Number of callbacks registered on a hook (all priorities).
 *
 * @param string $hook Hook.
 * @return int
 */
function dbgr_test_hook_count( $hook ) {
	$count = 0;
	if ( ! empty( $GLOBALS['dbgr_hooks'][ $hook ] ) ) {
		foreach ( $GLOBALS['dbgr_hooks'][ $hook ] as $callbacks ) {
			$count += count( $callbacks );
		}
	}
	return $count;
}

/**
 * Names of every hook that has at least one callback (used by the "inert" tests).
 *
 * @return array
 */
function dbgr_test_hook_names() {
	$names = array();
	foreach ( $GLOBALS['dbgr_hooks'] as $hook => $priorities ) {
		foreach ( $priorities as $callbacks ) {
			if ( ! empty( $callbacks ) ) {
				$names[] = $hook;
				break;
			}
		}
	}
	sort( $names );
	return $names;
}

