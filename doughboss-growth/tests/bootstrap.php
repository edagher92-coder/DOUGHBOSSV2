/**
 * DoughBoss Growth test bootstrap: a reusable WordPress stub harness.
 *
 * There is no WordPress and no MySQL in the test environment. This file provides enough of the WordPress
 * surface to exercise the companion's PHP for real:
 *
 *   - options, transients, cron, shortcodes, posts, menus, users and capabilities, nonces;
 *   - hooks with real add_action / add_filter / do_action / apply_filters semantics (priorities,
 *     accepted args, removal, did_action), cloned from WordPress's behaviour;
 *   - a fake $wpdb that records every query, can be forced to error, answers from scripted responders,
 *     and can optionally run against an in-memory SQLite database (use_sqlite()) so uniqueness,
 *     atomic UPDATE semantics and the real CREATE TABLE statements are exercised;
 *   - WP_Error, WP_REST_Request / Response / Server and a REST dispatcher with permission callbacks;
 *   - a wp_remote_* fake transport that FAILS THE TEST on any call that was not expected;
 *   - time control through DoughBoss_Growth::set_time_override();
 *   - esc_* / sanitize_* functions that behave like WordPress for the cases the plugin relies on.
 *
 * Guard rails the harness enforces for every test run:
 *   - writing an option, transient or cron hook that does not start with "doughboss_growth_" is a
 *     recorded FOREIGN WRITE, and so is any INSERT/UPDATE/DELETE/DROP/ALTER/CREATE against a table that
 *     is not {prefix}doughboss_growth_*. run.php fails the whole run if any foreign write was recorded;
 *   - any outbound HTTP call that a test did not declare fails that test.
 *
 * Later work packages add THEIR OWN stubs in tests/stubs-<module>.php (auto-loaded by run.php after this
 * file) and their own tests in tests/test-<module>.php. They do not edit this file.
 *
 * Everything here is PHP 7.4 compatible. Run with: php tests/run.php [name-filter ...]
 *
 * @package DoughBoss_Growth
 */

