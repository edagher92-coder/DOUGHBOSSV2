	/**
	 * @param string $query Query with placeholders.
	 * @param mixed  ...$args Arguments (or one array of them).
	 * @return string
	 */
	public function prepare( $query, ...$args ) {
		if ( 1 === count( $args ) && is_array( $args[0] ) ) {
			$args = $args[0];
		}
		$args  = array_values( $args );
		$index = 0;
		$count = preg_match_all( '/%(?:%|[sdf])/', $query, $all );
		$need  = 0;
		foreach ( $all[0] as $token ) {
			if ( '%%' !== $token ) {
				$need++;
			}
		}
		if ( $need !== count( $args ) ) {
			throw new LogicException( 'wpdb->prepare placeholder/argument mismatch: ' . $need . ' placeholders, ' . count( $args ) . ' args in: ' . $query );
		}
		unset( $count );
		$sql = preg_replace_callback(
			'/%(%|[sdf])/',
			function ( $m ) use ( &$index, $args ) {
				if ( '%' === $m[1] ) {
					return '%';
				}
				$value = $args[ $index++ ];
				if ( 'd' === $m[1] ) {
					return (string) (int) $value;
				}
				if ( 'f' === $m[1] ) {
					return (string) (float) $value;
				}
				return "'" . $this->escape_string( (string) $value ) . "'";
			},
			$query
		);
		$this->prepared_sql[] = $sql;
		return $sql;
	}

	/** @param string $value Value. @return string */
	private function escape_string( $value ) {
		if ( null !== $this->pdo ) {
			return str_replace( "'", "''", $value );
		}
		return str_replace( array( '\\', "'", "\0", "\n", "\r", "\x1a" ), array( '\\\\', "\\'", '\\0', '\\n', '\\r', '\\Z' ), $value );
	}

	/** @param string $sql SQL. @return int|bool */
	public function query( $sql ) {
		$result = $this->run( 'query', $sql );
		return $result;
	}

	/** @param string $sql SQL. @param int $x Column. @param int $y Row. @return mixed */
	public function get_var( $sql, $x = 0, $y = 0 ) {
		$rows = $this->run( 'get_var', $sql );
		if ( ! is_array( $rows ) || ! isset( $rows[ $y ] ) ) {
			return is_scalar( $rows ) ? $rows : null;
		}
		$row = array_values( (array) $rows[ $y ] );
		return isset( $row[ $x ] ) ? $row[ $x ] : null;
	}

	/** @param string $sql SQL. @param string $output Output type. @param int $y Row. @return mixed */
	public function get_row( $sql, $output = OBJECT, $y = 0 ) {
		$rows = $this->run( 'get_row', $sql );
		if ( ! is_array( $rows ) || ! isset( $rows[ $y ] ) ) {
			return null;
		}
		return $this->shape( $rows[ $y ], $output );
	}

	/** @param string $sql SQL. @param int $x Column. @return array */
	public function get_col( $sql, $x = 0 ) {
		$rows = $this->run( 'get_col', $sql );
		$out  = array();
		if ( is_array( $rows ) ) {
			foreach ( $rows as $row ) {
				$values = array_values( (array) $row );
				$out[]  = isset( $values[ $x ] ) ? $values[ $x ] : null;
			}
		}
		return $out;
	}

	/** @param string $sql SQL. @param string $output Output type. @return array */
	public function get_results( $sql, $output = OBJECT ) {
		$rows = $this->run( 'get_results', $sql );
		$out  = array();
		if ( is_array( $rows ) ) {
			foreach ( $rows as $row ) {
				$out[] = $this->shape( $row, $output );
			}
		}
		return $out;
	}

	/** @param string $table Table. @param array $data Data. @param array|null $format Formats. @return int|false */
	public function insert( $table, $data, $format = null ) {
		return $this->write_row( 'INSERT', $table, $data, $format );
	}

	/** @param string $table Table. @param array $data Data. @param array|null $format Formats. @return int|false */
	public function replace( $table, $data, $format = null ) {
		return $this->write_row( 'REPLACE', $table, $data, $format );
	}

	/** @param string $table Table. @param array $data Data. @param array $where Where. @return int|false */
	public function update( $table, $data, $where ) {
		$sets  = array();
		$conds = array();
		foreach ( $data as $column => $value ) {
			$sets[] = $column . ' = ' . $this->literal( $value );
		}
		foreach ( $where as $column => $value ) {
			$conds[] = $column . ' = ' . $this->literal( $value );
		}
		$this->prepared_sql[] = $sql = 'UPDATE ' . $table . ' SET ' . implode( ', ', $sets ) . ' WHERE ' . implode( ' AND ', $conds );
		return $this->run( 'query', $sql );
	}

	/** @param string $table Table. @param array $where Where. @return int|false */
	public function delete( $table, $where ) {
		$conds = array();
		foreach ( $where as $column => $value ) {
			$conds[] = $column . ' = ' . $this->literal( $value );
		}
		$this->prepared_sql[] = $sql = 'DELETE FROM ' . $table . ' WHERE ' . implode( ' AND ', $conds );
		return $this->run( 'query', $sql );
	}

	/** @param string $verb INSERT or REPLACE. @param string $table Table. @param array $data Data. @param mixed $format Formats. @return int|false */
	private function write_row( $verb, $table, $data, $format ) {
		unset( $format );
		$columns = array_keys( $data );
		$values  = array();
		foreach ( $data as $value ) {
			$values[] = $this->literal( $value );
		}
		$this->prepared_sql[] = $sql = $verb . ' INTO ' . $table . ' (' . implode( ', ', $columns ) . ') VALUES (' . implode( ', ', $values ) . ')';
		return $this->run( 'query', $sql );
	}

	/** @param mixed $value Value. @return string */
	private function literal( $value ) {
		if ( null === $value ) {
			return 'NULL';
		}
		if ( is_int( $value ) || is_float( $value ) ) {
			return (string) $value;
		}
		return "'" . $this->escape_string( (string) $value ) . "'";
	}

	/** @param mixed $row Row. @param string $output Output. @return mixed */
	private function shape( $row, $output ) {
		$row = (array) $row;
		if ( ARRAY_A === $output ) {
			return $row;
		}
		if ( ARRAY_N === $output ) {
			return array_values( $row );
		}
		return (object) $row;
	}

	/**
	 * Core execution path.
	 *
	 * @param string $method query|get_var|get_row|get_col|get_results.
	 * @param string $sql    SQL.
	 * @return mixed
	 */
	private function run( $method, $sql ) {
		$this->queries[]  = array( 'method' => $method, 'sql' => $sql );
		$this->last_query = $sql;
		$this->last_error = '';
		if ( ! in_array( $sql, $this->prepared_sql, true ) ) {
			$this->unprepared[] = $sql;
		}
		$this->check_foreign_write( $sql );

		$failed = $this->fail_all;
		foreach ( $this->fail_patterns as $pattern ) {
			if ( 1 === preg_match( $pattern, $sql ) ) {
				$failed = true;
			}
		}
		if ( $failed ) {
			$this->last_error = 'DBGR forced database error';
			return ( 'query' === $method ) ? false : null;
		}
		foreach ( $this->responders as $responder ) {
			if ( 1 === preg_match( $responder['pattern'], $sql ) ) {
				$result = is_callable( $responder['result'] ) ? call_user_func( $responder['result'], $sql, $method ) : $responder['result'];
				return $this->adapt_scripted( $method, $result );
			}
		}
		if ( null !== $this->pdo ) {
			return $this->run_sqlite( $method, $sql );
		}
		// Without SQLite: SHOW TABLES LIKE answers from the tables dbDelta "created".
		if ( 1 === preg_match( "/^SHOW TABLES LIKE '(.*)'$/is", $sql, $m ) ) {
			$name  = str_replace( array( '\\_', '\\%' ), array( '_', '%' ), stripslashes( $m[1] ) );
			$found = in_array( $name, $this->tables_created, true ) ? $name : null;
			return ( null === $found ) ? array() : array( array( $found ) );
		}
		$this->rows_affected = 0;
		return ( 'query' === $method ) ? 0 : array();
	}

	/** @param string $method Method. @param mixed $result Scripted result. @return mixed */
	private function adapt_scripted( $method, $result ) {
		if ( 'query' === $method ) {
			return is_array( $result ) ? count( $result ) : $result;
		}
		if ( 'get_var' === $method ) {
			return array( array( $result ) );
		}
		if ( is_array( $result ) ) {
			if ( 'get_row' === $method && ! empty( $result ) && ! isset( $result[0] ) ) {
				return array( $result );
			}
			return $result;
		}
		return array();
	}

	/** @param string $sql SQL. @return void */
	private function check_foreign_write( $sql ) {
		if ( 1 !== preg_match( '/^\s*(INSERT(?:\s+IGNORE)?\s+INTO|REPLACE\s+INTO|UPDATE|DELETE\s+FROM|DROP\s+TABLE(?:\s+IF\s+EXISTS)?|ALTER\s+TABLE|CREATE\s+TABLE(?:\s+IF\s+NOT\s+EXISTS)?|TRUNCATE(?:\s+TABLE)?)\s+`?([A-Za-z0-9_]+)`?/i', $sql, $m ) ) {
			return;
		}
		if ( 0 !== strpos( $m[2], $this->prefix . DBGR_TEST_PREFIX ) ) {
			$this->foreign_writes[]           = $m[1] . ' ' . $m[2];
			$GLOBALS['dbgr_foreign_writes'][] = $GLOBALS['doughboss_test_results']['current'] . ': SQL write to ' . $m[2];
		}
	}

	/* ----- harness controls ----- */

	/** @param bool $flag Fail every statement. @return void */
	public function fail_all( $flag = true ) {
		$this->fail_all = (bool) $flag;
	}

	/** @param string $pattern Regex. @return void */
	public function fail_on( $pattern ) {
		$this->fail_patterns[] = $pattern;
	}

	/** @return void */
	public function clear_failures() {
		$this->fail_all      = false;
		$this->fail_patterns = array();
	}

	/**
	 * Script an answer. query(): int rows affected (or false); get_var(): scalar; get_row(): assoc array;
	 * get_col()/get_results(): list of rows. A callable receives ( $sql, $method ).
	 *
	 * @param string $pattern Regex tested against the SQL.
	 * @param mixed  $result  Result or callable.
	 * @return void
	 */
	public function respond( $pattern, $result ) {
		$this->responders[] = array( 'pattern' => $pattern, 'result' => $result );
	}

	/** @param string $pattern Regex. @return array Statements matching. */
	public function queries_matching( $pattern ) {
		$out = array();
		foreach ( $this->queries as $q ) {
			if ( 1 === preg_match( $pattern, $q['sql'] ) ) {
				$out[] = $q['sql'];
			}
		}
		return $out;
	}

	/** @return void */
	public function reset_log() {
		$this->queries      = array();
		$this->unprepared   = array();
		$this->prepared_sql = array();
	}

	/**
	 * Switch to an in-memory SQLite database.
	 *
	 * @return void
	 */
	public function use_sqlite() {
		$this->pdo = new PDO( 'sqlite::memory:' );
		$this->pdo->setAttribute( PDO::ATTR_ERRMODE, PDO::ERRMODE_EXCEPTION );
		$this->pdo->setAttribute( PDO::ATTR_DEFAULT_FETCH_MODE, PDO::FETCH_ASSOC );
	}

	/** @return bool */
	public function is_sqlite() {
		return null !== $this->pdo;
	}

	/**
	 * Run raw SQL on the SQLite database, bypassing recording (for test fixtures).
	 *
	 * @param string $sql SQL.
	 * @return array Rows (for SELECT) or an empty array.
	 */
	public function sqlite_raw( $sql ) {
		$stmt = $this->pdo->query( $sql );
		return $stmt ? $stmt->fetchAll() : array();
	}

	/**
	 * Register a MySQL CREATE TABLE statement. In SQLite mode it is translated and executed; otherwise the
	 * table is only marked as existing. Handles the column types, AUTO_INCREMENT, PRIMARY KEY, KEY and
	 * UNIQUE KEY forms the companion uses.
	 *
	 * @param string $sql CREATE TABLE statement.
	 * @return void
	 */
	public function create_table_from_mysql( $sql ) {
		if ( 1 !== preg_match( '/^\s*CREATE TABLE\s+`?([A-Za-z0-9_]+)`?\s*\((.*)\)\s*[^)]*;?\s*$/s', $sql, $m ) ) {
			return;
		}
		$table = $m[1];
		if ( ! in_array( $table, $this->tables_created, true ) ) {
			$this->tables_created[] = $table;
		}
		if ( null === $this->pdo ) {
			return;
		}
		$columns = array();
		$indexes = array();
		foreach ( $this->split_top_level( $m[2] ) as $part ) {
			$part = trim( $part );
			if ( 1 === preg_match( '/^PRIMARY\s+KEY\s*\(([^)]*)\)/i', $part, $k ) ) {
				if ( ! $this->has_autoincrement( $columns ) ) {
					$columns[] = 'PRIMARY KEY (' . $this->strip_prefix_lengths( $k[1] ) . ')';
				}
				continue;
			}
			if ( 1 === preg_match( '/^UNIQUE\s+KEY\s+`?([A-Za-z0-9_]+)`?\s*\((.*)\)$/is', $part, $k ) ) {
				$indexes[] = 'CREATE UNIQUE INDEX ' . $table . '_' . $k[1] . ' ON ' . $table . ' (' . $this->strip_prefix_lengths( $k[2] ) . ')';
				continue;
			}
			if ( 1 === preg_match( '/^(?:KEY|INDEX)\s+`?([A-Za-z0-9_]+)`?\s*\((.*)\)$/is', $part, $k ) ) {
				$indexes[] = 'CREATE INDEX ' . $table . '_' . $k[1] . ' ON ' . $table . ' (' . $this->strip_prefix_lengths( $k[2] ) . ')';
				continue;
			}
			$columns[] = $this->translate_column( $part );
		}
		$this->pdo->exec( 'DROP TABLE IF EXISTS ' . $table );
		$this->pdo->exec( 'CREATE TABLE ' . $table . ' (' . implode( ', ', $columns ) . ')' );
		foreach ( $indexes as $index_sql ) {
			$this->pdo->exec( $index_sql );
		}
	}

	/** @param array $columns Column definitions so far. @return bool */
	private function has_autoincrement( array $columns ) {
		foreach ( $columns as $column ) {
			if ( false !== stripos( $column, 'AUTOINCREMENT' ) ) {
				return true;
			}
		}
		return false;
	}

	/** @param string $cols Column list. @return string */
	private function strip_prefix_lengths( $cols ) {
		return preg_replace( '/\(\s*\d+\s*\)/', '', $cols );
	}

	/** @param string $definition MySQL column definition. @return string */
	private function translate_column( $definition ) {
		if ( 1 !== preg_match( '/^`?([A-Za-z0-9_]+)`?\s+([A-Za-z]+)(?:\s*\([^)]*\))?(.*)$/is', $definition, $m ) ) {
			return $definition;
		}
		$name = $m[1];
		$type = strtolower( $m[2] );
		$rest = $m[3];
		if ( false !== stripos( $rest, 'AUTO_INCREMENT' ) ) {
			return $name . ' INTEGER PRIMARY KEY AUTOINCREMENT';
		}
		$map  = array(
			'bigint' => 'INTEGER', 'int' => 'INTEGER', 'integer' => 'INTEGER', 'smallint' => 'INTEGER', 'tinyint' => 'INTEGER', 'mediumint' => 'INTEGER',
			'decimal' => 'NUMERIC', 'float' => 'REAL', 'double' => 'REAL',
		);
		$sql_type = isset( $map[ $type ] ) ? $map[ $type ] : 'TEXT';
		$rest     = preg_replace( '/\b(unsigned|zerofill)\b/i', '', $rest );
		$rest     = preg_replace( '/\b(CHARACTER SET|CHARSET)\s+\w+/i', '', $rest );
		$rest     = preg_replace( '/\bCOLLATE\s+\w+/i', '', $rest );
		$rest     = preg_replace( '/\bON UPDATE\s+CURRENT_TIMESTAMP(\(\))?/i', '', $rest );
		return $name . ' ' . $sql_type . ' ' . trim( $rest );
	}

	/** @param string $text Text. @return array Parts split on top-level commas. */
	private function split_top_level( $text ) {
		$parts = array();
		$depth = 0;
		$buf   = '';
		$len   = strlen( $text );
		for ( $i = 0; $i < $len; $i++ ) {
			$ch = $text[ $i ];
			if ( '(' === $ch ) {
				$depth++;
			} elseif ( ')' === $ch ) {
				$depth--;
			}
			if ( ',' === $ch && 0 === $depth ) {
				$parts[] = $buf;
				$buf     = '';
				continue;
			}
			$buf .= $ch;
		}
		if ( '' !== trim( $buf ) ) {
			$parts[] = $buf;
		}
		return $parts;
	}

	/** @param string $method Method. @param string $sql SQL. @return mixed */
	private function run_sqlite( $method, $sql ) {
		$translated = $sql;
		$translated = preg_replace( '/^\s*INSERT\s+IGNORE\s+INTO/i', 'INSERT OR IGNORE INTO', $translated );
		$translated = preg_replace( '/^\s*REPLACE\s+INTO/i', 'INSERT OR REPLACE INTO', $translated );
		if ( 1 === preg_match( "/^SHOW TABLES LIKE '(.*)'$/is", $translated, $m ) ) {
			$like       = str_replace( "''", "'", $m[1] );
			$translated = "SELECT name FROM sqlite_master WHERE type = 'table' AND name LIKE '" . str_replace( "'", "''", $like ) . "' ESCAPE '\\'";
		}
		try {
			if ( 1 === preg_match( '/^\s*(SELECT|SHOW|PRAGMA|WITH)\b/i', $translated ) ) {
				$stmt = $this->pdo->query( $translated );
				$rows = $stmt->fetchAll();
				$this->rows_affected = 0;
				return ( 'query' === $method ) ? count( $rows ) : $rows;
			}
			$affected            = $this->pdo->exec( $translated );
			$this->rows_affected = (int) $affected;
			$this->insert_id     = (int) $this->pdo->lastInsertId();
			return $this->rows_affected;
		} catch ( PDOException $e ) {
			$this->last_error = $e->getMessage();
			return ( 'query' === $method ) ? false : null;
		}
	}
}

