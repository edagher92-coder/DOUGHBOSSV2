/**
 * Remove a directory tree (test scratch space). Symlinks are unlinked, never followed.
 *
 * @param string $dir Directory.
 * @return void
 */
function dbgr_test_rmdir( $dir ) {
	if ( ! is_dir( $dir ) || is_link( $dir ) ) {
		if ( is_link( $dir ) ) {
			unlink( $dir );
		}
		return;
	}
	foreach ( scandir( $dir ) as $entry ) {
		if ( '.' === $entry || '..' === $entry ) {
			continue;
		}
		$path = $dir . '/' . $entry;
		if ( is_dir( $path ) && ! is_link( $path ) ) {
			dbgr_test_rmdir( $path );
		} else {
			unlink( $path );
		}
	}
	rmdir( $dir );
}

/**
 * Whether this PHP can really start a sub-process. Probed once: proc_open() may exist yet be unusable (a
 * sandboxed or WebAssembly PHP), in which case tests that need a sub-process are skipped, not failed.
 *
 * @return bool
 */
function dbgr_test_can_subprocess() {
	static $can = null;
	if ( null !== $can ) {
		return $can;
	}
	$can = false;
	if ( function_exists( 'proc_open' ) && defined( 'PHP_BINARY' ) && '' !== PHP_BINARY && is_executable( PHP_BINARY ) ) {
		$pipes   = array();
		$process = @proc_open( array( PHP_BINARY, '-r', 'echo "dbgr-ok";' ), array( 1 => array( 'pipe', 'w' ), 2 => array( 'pipe', 'w' ) ), $pipes );
		if ( is_resource( $process ) ) {
			$out = stream_get_contents( $pipes[1] );
			fclose( $pipes[1] );
			fclose( $pipes[2] );
			proc_close( $process );
			$can = ( 'dbgr-ok' === $out );
		}
	}
	return $can;
}

/**
 * Run PHP code in a fresh process that loads this bootstrap (and, by default, the tests/stubs-*.php files).
 * Use it for anything that depends on a constant being absent or set (core version, kill switch, uninstall
 * flag).
 *
 * @param string $code        Code to run after the bootstrap (no opening tag).
 * @param string $prelude     Code to run BEFORE the bootstrap (for example define('DOUGHBOSS_VERSION','2.43.2');).
 * @param bool   $load_stubs  False to skip tests/stubs-*.php (for example to test "DoughBoss core is absent").
 * @return array { exit: int, out: string, err: string }
 */
function dbgr_test_subprocess( $code, $prelude = '', $load_stubs = true ) {
	$file   = tempnam( sys_get_temp_dir(), 'dbgr-sub-' );
	$source = "<?php\n" . $prelude . "\nrequire " . var_export( __FILE__, true ) . ";\n" . ( $load_stubs ? "dbgr_test_load_stubs();\n" : '' ) . $code . "\n";
	file_put_contents( $file, $source );
	$descriptors = array( 1 => array( 'pipe', 'w' ), 2 => array( 'pipe', 'w' ) );
	$process     = proc_open( array( PHP_BINARY, '-d', 'display_errors=stderr', $file ), $descriptors, $pipes );
	if ( ! is_resource( $process ) ) {
		@unlink( $file );
		return array( 'exit' => -1, 'out' => '', 'err' => 'proc_open failed' );
	}
	$out  = stream_get_contents( $pipes[1] );
	$err  = stream_get_contents( $pipes[2] );
	fclose( $pipes[1] );
	fclose( $pipes[2] );
	$exit = proc_close( $process );
	@unlink( $file );
	return array( 'exit' => $exit, 'out' => (string) $out, 'err' => (string) $err );
}

/**
 * Load every tests/stubs-*.php (module stubs). Safe to call more than once.
 *
 * @return array Files loaded.
 */
function dbgr_test_load_stubs() {
	static $loaded = array();
	$files         = glob( __DIR__ . '/stubs-*.php' );
	sort( $files );
	foreach ( $files as $file ) {
		if ( ! isset( $loaded[ $file ] ) ) {
			$loaded[ $file ] = true;
			require_once $file;
		}
	}
	return array_keys( $loaded );
}

