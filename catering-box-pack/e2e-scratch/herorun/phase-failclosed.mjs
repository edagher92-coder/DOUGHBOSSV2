// Phase E (core C 2.43.2: the hero backdrop is an <img>): the edit must fail closed and the page must be core's own.
import { chromium, BASE, HERE, VID, STATE, VIDEOS, ok, note, tally, sha, adminLogin, anon, get, setSwitches, heroStatus, fs, log } from "./lib.mjs";
const browser = await chromium.launch();
const { p } = await adminLogin(browser);
const a = await anon();
await p.goto(BASE + "/wp-admin/options-reading.php");
await p.uncheck("#blog_public");
await Promise.all([p.waitForNavigation(), p.click("#submit")]);
await p.goto(BASE + "/wp-admin/plugins.php");
await Promise.all([p.waitForNavigation(), p.click('tr[data-plugin="doughboss-growth-box/doughboss-growth-box.php"] .deactivate a')]);
const base = await get(a, "/");
ok((await get(a, "/")) === base, "core 2.43.2 baseline (plugin inactive) is stable");
const heroOf = (h) => (h.match(/<section class="db-manoush-hero.*?<\/section>/s) || [""])[0];
note("core 2.43.2 hero backdrop markup: " + (heroOf(base).match(/<picture>.*?<\/picture>|<img class="db-mh-backdrop"[^>]*>/s) || [""])[0].replace(BASE, "").slice(0, 260));
ok(/<img[^>]*class="db-mh-backdrop"/.test(heroOf(base)) && !/<div class="db-mh-backdrop"/.test(heroOf(base)), "core 2.43.2 draws the backdrop as an <img> (the edit cannot apply)");
await p.goto(BASE + "/wp-admin/plugins.php");
await Promise.all([p.waitForNavigation(), p.click('tr[data-plugin="doughboss-growth-box/doughboss-growth-box.php"] .activate a')]);
// the five videos inside the media plugin (also exercises the plugin-folder source)
const heroDir = STATE + "/src/plugins/doughboss-growth-media/assets/hero";
for (const v of VIDEOS) fs.copyFileSync(VID + "/" + v, heroDir + "/" + v);
await setSwitches(p, { home_hero_video: true, hero_chip: true });
let st = await heroStatus(p);
ok(VIDEOS.every((v) => st.rows[v].where === "Media plugin folder") && /Running/.test(st.state), "five videos found in the media plugin folder; status says Running before the first page view");
const first = await get(a, "/");
fs.writeFileSync(HERE + "/out/c-first.html", first);
ok(heroOf(first) === heroOf(base), "FIRST view after switching on: the hero section is byte-identical to core's own (re-rendered without our change)");
ok(!/has-dbgr-video|<video|dbgr-hero-chip|dbgr-hero-poster-1080\.webp\?ver=[0-9]+'\)/.test(first.replace(/<link rel="preload"[^>]*>/g, "")), "  no video, chip, class or poster address in the body");
note("first view differs from baseline only in the <head> (preload, stylesheet) and footer script: " + (first !== base));
const second = await get(a, "/");
ok(second === base, "SECOND view: the whole page is byte-identical to the plugin-inactive baseline (" + second.length + " bytes): the failure marker switched the feature off");
st = await heroStatus(p);
ok(/not drawn the way this plugin expects/.test(st.state), "settings screen explains: " + st.state);
await p.screenshot({ path: HERE + "/shots/admin-settings-failclosed-1440.png", fullPage: true });
await setSwitches(p, { home_hero_video: true, hero_chip: true });
st = await heroStatus(p);
ok(/Running/.test(st.state), "saving the screen clears the failure marker (it will be tried again)");
const again = await get(a, "/");
ok(heroOf(again) === heroOf(base), "tried again on the next view: fails closed again, hero untouched");
ok((await get(a, "/")) === base, "and the view after that is byte-identical to baseline again");
fs.writeFileSync(HERE + "/out/phase-failclosed.log", log.join("\n"));
await browser.close();
const t = tally();
console.log(`\nphase E: ${t.pass} passed, ${t.fail} failed`);
process.exit(t.fail ? 1 : 0);
